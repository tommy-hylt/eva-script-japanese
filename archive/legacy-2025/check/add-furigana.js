// Main processing
function processFile() {
  const inputPath = path.join(__dirname, 'completed-missing-lines.json');
  const data = JSON.parse(fs.readFileSync(inputPath, 'utf8'));

  console.log(`Processing ${data.length} entries with furigana...`);

  const processed = data.map((entry, index) => {
    if (index % 50 === 0) {
      console.log(`  Progress: ${index}/${data.length}`);
    }

    const originalJapanese = entry.segments[0];
    const newSegments = convertToSegments(originalJapanese);

    return {
      time: entry.time,
      character: entry.character,
      segments: newSegments,
      english: entry.english
    };
  });

  const outputPath = path.join(__dirname, 'missing-lines-with-furigana.json');
  fs.writeFileSync(outputPath, JSON.stringify(processed, null, 2), 'utf8');

  console.log(`\n✓ Completed! Saved to: ${outputPath}`);
}

processFile();
