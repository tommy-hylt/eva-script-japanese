def process_file(input_file, output_file):
    """Process a JSON file to convert hiragana fields"""
    with open(input_file, 'r', encoding='utf-8') as f:
        data = json.load(f)

    for entry in data:
        if 'japanese' in entry and 'hiragana' in entry:
            # For now, convert katakana to hiragana
            entry['hiragana'] = convert_to_hiragana(entry['japanese'])

    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

